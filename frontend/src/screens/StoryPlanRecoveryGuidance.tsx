export function StoryPlanRecoveryGuidance({ hasDiagrams, confirmed = true }: {
  hasDiagrams: boolean; confirmed?: boolean;
}) {
  return <section className="notice" aria-label="보고 계획 복구 안내">
    <h4>{confirmed ? "보고 계획을 다시 확인해야 합니다" : "보고 계획이 달라졌을 때의 복구 방법"}</h4>
    <p>{confirmed
      ? "보고 정보, 장 구성, 자료 또는 보고 계획이 달라져 현재 계획으로 작업을 계속할 수 없습니다."
      : "보고 정보, 장 구성, 자료 또는 보고 계획이 달라졌다면 아래 복구 방법을 확인해 주세요. 이 도움말은 현재 계획을 검사한 결과가 아닙니다."}</p>
    <ol>
      <li>자료 탭과 보고 정보, 장 구성의 변경 내용을 확인해 주세요. 이전 상태를 정확히 복원할 수 있다면 복원한 뒤 다시 확인할 수 있습니다.</li>
      <li>스냅샷은 보고서 편집 내용을 복원하며 자료 파일은 복원하지 않습니다. 자료가 바뀌었다면 자료도 별도로 확인해야 합니다.</li>
      <li>구조안 탭의 ‘기존 편집을 보존하며 계획 재작성’에서 새 계획을 먼저 확인할 수 있습니다. 장 수와 본문은 유지하며, 도식이 의존하는 원자료가 바뀐 경우에는 재작성을 중단합니다. 적용 뒤 본문도 별도로 재검토해야 합니다.</li>
      {hasDiagrams ? <li>
        저장된 도식이 있는 프로젝트의 전체 구조안 다시 생성은 아직 지원하지 않습니다.
        새 자료로 다시 만들어야 한다면 기존 프로젝트를 보존하고 별도 프로젝트에서 자료와 보고 질문으로 시작해 주세요.
        기존 도식과 근거 연결은 자동으로 옮겨지지 않습니다.
      </li> : <li>
        이전 상태로 되돌릴 수 없다면 작성 중인 내용을 보관한 뒤 구조안 탭에서 보고 질문으로 다시 생성해 주세요.
        새 구조안을 승인하면 기존 장 내용이 교체될 수 있으므로 승인 전 안내를 확인해 주세요.
      </li>}
    </ol>
  </section>;
}
